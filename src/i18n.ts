export type Key = keyof typeof en;

function steamLanguage(): string {
  // The Steam client knows the UI language better than the CEF navigator does.
  const lm = (window as any).LocalizationManager;
  return (lm?.m_rgLocalesToUse?.[0] as string | undefined) ?? navigator.language ?? "en";
}

const strings = /^(zh|schinese|tchinese)/i.test(steamLanguage()) ? zh : en;

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return strings[key].replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}
