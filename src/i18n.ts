export type Key = keyof typeof en;

function steamLanguage(): string {
  // The Steam client knows the UI language better than the CEF navigator does.
  const lm = (window as any).LocalizationManager;
  return (lm?.m_rgLocalesToUse?.[0] as string | undefined) ?? navigator.language ?? "en";
}

type Lang = "en" | "zh" | "zh_tw" | "ja";

function pickLang(code: string): Lang {
  // Steam reports codes such as "zh-cn", "zh-tw" and "ja"; older builds used names like "tchinese".
  if (/^(zh-(tw|hk|mo|hant)|tchinese)/i.test(code)) return "zh_tw";
  if (/^(zh|schinese)/i.test(code)) return "zh";
  if (/^(ja|japanese)/i.test(code)) return "ja";
  return "en";
}

const lang = pickLang(steamLanguage());
const strings = { en, zh, zh_tw, ja }[lang];

// Steam's font stack has no CJK font, so CJK text falls back per weight, and at 600 that lands on a
// serif face. Naming the SteamOS Noto Sans CJK variant for the language keeps it sans and bold.
const CJK_FONT: Record<Lang, string | null> = {
  en: null,
  zh: "Noto Sans CJK SC",
  zh_tw: "Noto Sans CJK TC",
  ja: "Noto Sans CJK JP",
};
export const FONT_FAMILY = ['"Motiva Sans"', CJK_FONT[lang] && `"${CJK_FONT[lang]}"`, "Arial", "Helvetica", "sans-serif"]
  .filter(Boolean)
  .join(", ");

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return strings[key].replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}
